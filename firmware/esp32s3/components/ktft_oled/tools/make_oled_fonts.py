"""Generates components/ktft_oled/oled_fonts.cpp: bitmap fonts for the little OLED, rendered from
DejaVu Sans Bold / Sans Condensed Bold (free licence, see components/ktft_oled/FONT-LICENSE.txt).

    python3 tools/make_oled_fonts.py [folder with the DejaVu .ttf files]

Each font is proportional; glyphs are stored column by column, top bit first in each byte
(the same order the SSD1306 uses), ceil(height/8) bytes per column.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the ktft_oled component
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu"
BIG_CHARS = " 0123456789%-./:!?ABCDEFGHIJKLMNOPQRSTUVWXYZ"
SMALL_CHARS = "".join(chr(c) for c in range(32, 127))

# (name, ttf, pixel size passed to FreeType, cell height, characters, threshold)
FONTS = [
    ("small", "DejaVuSans-Bold", 9, 10, SMALL_CHARS, 100),            # ~7 px capitals: labels, notes
    ("medium", "DejaVuSansCondensed-Bold", 18, 17, BIG_CHARS, 120),   # 13 px digits: status lines
    ("big", "DejaVuSansCondensed-Bold", 34, 27, BIG_CHARS, 128),      # 25 px digits: temperatures
    ("huge", "DejaVuSansCondensed-Bold", 52, 40, BIG_CHARS, 128),     # 38 px digits: print percentage
]


def render(name, ttf, size, height, chars, threshold):
    font = ImageFont.truetype(os.path.join(FONT_DIR, ttf + ".ttf"), size)
    ascent, _ = font.getmetrics()
    # place the baseline so digit tops sit at row 0 (digits have no descenders)
    top = font.getbbox("0")[1]
    glyphs = []
    for ch in chars:
        adv = int(round(font.getlength(ch))) if ch != " " else max(2, size // 4)
        w = max(1, adv)
        img = Image.new("L", (w + 2, height), 0)
        ImageDraw.Draw(img).text((0, -top), ch, font=font, fill=255)
        # trim empty columns on both sides, keep a 1 px gap
        cols = [x for x in range(img.width) if any(img.getpixel((x, y)) >= threshold for y in range(height))]
        if cols and ch != " ":
            x0, x1 = cols[0], cols[-1]
        else:
            x0, x1 = 0, w - 1
        bits = []
        for x in range(x0, x1 + 1):
            col = 0
            for y in range(height):
                if img.getpixel((x, y)) >= threshold:
                    col |= 1 << y
            bits.append(col)
        glyphs.append((ch, bits))
    return glyphs


def emit():
    out = ['// Generated by tools/make_oled_fonts.py from DejaVu Sans (Condensed) Bold. Do not edit.',
           '// Font licence: see components/ktft_oled/FONT-LICENSE.txt (Bitstream Vera / DejaVu, free).',
           '#include "oled.hpp"', '', 'namespace ktft {', '']
    for name, ttf, size, height, chars, thr in FONTS:
        glyphs = render(name, ttf, size, height, chars, thr)
        nbytes = (height + 7) // 8
        data, offsets, widths = [], [], []
        for ch, cols in glyphs:
            offsets.append(len(data))
            widths.append(len(cols))
            for c in cols:
                for b in range(nbytes):
                    data.append((c >> (8 * b)) & 0xFF)
        esc = chars.replace("\\", "\\\\").replace('"', '\\"')
        out.append("static const uint8_t %s_data[] = {" % name)
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join("0x%02X" % v for v in data[i:i + 24]) + ",")
        out.append("};")
        out.append("static const uint16_t %s_off[] = {%s};" % (name, ", ".join(map(str, offsets))))
        out.append("static const uint8_t %s_w[] = {%s};" % (name, ", ".join(map(str, widths))))
        out.append('const OledFont kFont%s = {"%s", %d, %d, %s_data, %s_off, %s_w};' %
                   (name.capitalize(), esc, len(chars), height, name, name, name))
        out.append("")
    out.append("}  // namespace ktft")
    path = os.path.join(ROOT, "oled_fonts.cpp")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    emit()
