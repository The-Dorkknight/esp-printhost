"""Reference results for the shaper calibration port (host/src/resonance.cpp), from Klipper's own
shaper_calibrate.py, on synthetic accelerometer data that test_resonance.cpp generates identically.

    python3 host/tools/shaper_reference.py <klipper checkout>/klippy/extras > host/test/shaper_ref.h

Needs numpy. Klipper's files are imported from the checkout, not copied into this repository.
"""
import importlib, math, os, sys, types

import numpy as np

FS = 3200.0
SECONDS = 12.0


def lcg_seq(n, seed):
    out = np.empty(n)
    s = seed
    for i in range(n):
        s = (s * 1103515245 + 12345) % 2147483648
        out[i] = s / 2147483648.0
    return out


def synth():
    """The test signal: many sinusoids shaped by two frame resonances, plus a little noise."""
    n = int(FS * SECONDS)
    t = np.arange(n) / FS
    freqs = 5.0 + 0.25 * np.arange(781)
    data = np.zeros((n, 4))
    data[:, 0] = t
    for axis, (f0, zeta, gain, seed) in enumerate([(47.3, 0.08, 3000.0, 11), (38.1, 0.1, 1500.0, 23), (90.0, 0.2, 200.0, 37)]):
        phases = 2 * math.pi * lcg_seq(len(freqs), seed)
        r = freqs / f0
        amp = gain / np.sqrt((1 - r * r) ** 2 + (2 * zeta * r) ** 2) / np.sqrt(len(freqs))
        x = np.zeros(n)
        for k in range(len(freqs)):
            x += amp[k] * np.sin(2 * math.pi * freqs[k] * t + phases[k])
        x += 20.0 * (lcg_seq(n, seed + 1000) - 0.5) + (9806.65 if axis == 2 else 0.0)
        data[:, axis + 1] = x
    return data


def main():
    extras = sys.argv[1]
    pkg = types.ModuleType("extras")
    pkg.__path__ = [extras]
    sys.modules["extras"] = pkg
    sc = importlib.import_module("extras.shaper_calibrate")
    helper = sc.ShaperCalibrate(None)
    cal = helper.calc_freq_response(synth())
    cal.set_numpy(np)
    cal.normalize_to_frequencies()
    best, allsh = helper.find_best_shaper(cal, scv=5.0, max_freq=1.5 * 135.0)
    print("// Generated by host/tools/shaper_reference.py from Klipper's shaper_calibrate.py. Do not edit.")
    print("#pragma once")
    print("struct ShaperRef { const char* name; double freq, vibrs, smoothing, max_accel; };")
    print("static const ShaperRef SHAPER_REF[] = {")
    for s in allsh:
        print('    {"%s", %.4f, %.6f, %.6f, %.1f},' % (s.name, s.freq, s.vibrs, s.smoothing, s.max_accel))
    print("};")
    print('static const char* SHAPER_REF_BEST = "%s";' % best.name)
    # a few PSD points (normalised) to check the spectrum itself
    print("static const double PSD_REF[][2] = {")
    for f in (10.9375, 25.0, 38.28125, 47.1875, 60.9375, 90.0, 150.0):
        i = int(np.argmin(np.abs(cal.freq_bins - f)))
        print("    {%.6f, %.9g}," % (cal.freq_bins[i], cal.psd_sum[i]))
    print("};")


if __name__ == "__main__":
    main()
