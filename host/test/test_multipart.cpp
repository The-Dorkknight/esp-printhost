// Slicer uploads (multipart/form-data, as PrusaSlicer / OrcaSlicer send to OctoPrint) and G-code
// thumbnails.
#include "check.h"
#include "ph/multipart.h"

#include <string>
#include <vector>

using namespace ph;

namespace {
struct Got {
    std::vector<Multipart::Part> parts;
    std::vector<std::string> bodies;
    int ends = 0;
};

bool run(const std::string& boundary, const std::string& body, size_t chunk, Got& g, std::string* err = nullptr) {
    Multipart mp(boundary);
    mp.on_part = [&](const Multipart::Part& p) {
        g.parts.push_back(p);
        g.bodies.emplace_back();
        return true;
    };
    mp.on_data = [&](const char* d, size_t n) {
        g.bodies.back().append(d, n);
        return true;
    };
    mp.on_part_end = [&]() {
        g.ends++;
        return true;
    };
    for (size_t i = 0; i < body.size(); i += chunk)
        if (!mp.feed(body.data() + i, std::min(chunk, body.size() - i))) {
            if (err) *err = mp.error();
            return false;
        }
    return mp.done();
}

// what PrusaSlicer's OctoPrint upload looks like (curl-built form), with a file that itself contains
// "--" and CRLFs and a near-miss of the boundary
std::string slicer_form(const std::string& b, const std::string& file) {
    return "--" + b + "\r\n"
           "Content-Disposition: form-data; name=\"print\"\r\n\r\n"
           "true\r\n"
           "--" + b + "\r\n"
           "Content-Disposition: form-data; name=\"path\"\r\n\r\n"
           "\r\n"
           "--" + b + "\r\n"
           "Content-Disposition: form-data; name=\"file\"; filename=\"benchy 0.2mm.gcode\"\r\n"
           "Content-Type: application/octet-stream\r\n\r\n" +
           file + "\r\n"
           "--" + b + "--\r\n";
}
}  // namespace

static void test_multipart_parse() {
    std::string b = "------------------------3f1e2d0c9b8a7f6e";
    std::string file = "; generated by PrusaSlicer\r\nG28\r\n--not a boundary\r\n\r\n--" + b.substr(0, 20) +
                       "x\r\nG1 X10 Y10\nM84\n";
    std::string body = slicer_form(b, file);
    for (size_t chunk : {size_t(1), size_t(3), size_t(7), size_t(64), size_t(4096)}) {
        Got g;
        CHECK(run(b, body, chunk, g));
        CHECK(g.parts.size() == 3 && g.ends == 3);
        if (g.parts.size() == 3) {
            CHECK(g.parts[0].name == "print" && g.parts[0].filename.empty() && g.bodies[0] == "true");
            CHECK(g.parts[1].name == "path" && g.bodies[1].empty());
            CHECK(g.parts[2].name == "file" && g.parts[2].filename == "benchy 0.2mm.gcode");
            CHECK(g.parts[2].type == "application/octet-stream");
            CHECK(g.bodies[2] == file);
        }
    }
    // preamble, LF-less epilogue, quoted boundary in the header
    std::string bb;
    CHECK(Multipart::boundary_from_content_type("multipart/form-data; boundary=\"" + b + "\"", bb) && bb == b);
    CHECK(Multipart::boundary_from_content_type("Multipart/Form-Data;boundary=abc", bb) && bb == "abc");
    CHECK(!Multipart::boundary_from_content_type("application/octet-stream", bb));
    CHECK(!Multipart::boundary_from_content_type("multipart/form-data", bb));
    Got g2;
    CHECK(run("abc", "ignored preamble\r\n--abc\r\nContent-Disposition: form-data; name=\"x\"\r\n\r\n1\r\n--abc--", 5, g2));
    CHECK(g2.parts.size() == 1 && g2.bodies[0] == "1");
    // malformed: no Content-Disposition; truncated (never done)
    Got g3;
    std::string err;
    CHECK(!run("abc", "--abc\r\nX: y\r\n\r\nhi\r\n--abc--", 4, g3, &err) && err.find("Content-Disposition") != std::string::npos);
    Got g4;
    CHECK(!run(b, body.substr(0, body.size() - 10), 50, g4));
    CHECK(g4.parts.size() == 3 && g4.ends == 2);
    // a callback can stop it (e.g. the SD card is full)
    Multipart mp(b);
    mp.on_data = [](const char*, size_t) { return false; };
    CHECK(!mp.feed(body.data(), body.size()) && mp.error() == "stopped");
}

static void test_thumbnails() {
    std::string g =
        "; generated by PrusaSlicer 2.8.1\n"
        ";\n"
        "; thumbnail begin 16x16 8\n"
        "; AAAABBBB\n"
        "; thumbnail end\n"
        ";\n"
        "; thumbnail_QOI begin 300x300 4\n"
        "; QQQQ\n"
        "; thumbnail_QOI end\n"
        "; thumbnail_JPG begin 220x124 12\n"
        "; /9j/4AAQ\n"
        "; SkZJ\n"
        "; thumbnail_JPG end\n"
        "; thumbnail begin 600x600 4\n"
        "; WWWW\n"
        "; thumbnail end\n"
        "G28\n";
    GcodeThumbnail t;
    CHECK(find_gcode_thumbnail(g, 400, t));
    CHECK(t.w == 220 && t.h == 124 && t.format == "jpg" && t.base64 == "/9j/4AAQSkZJ");
    CHECK(find_gcode_thumbnail(g, 100, t) && t.w == 16 && t.format == "png" && t.base64 == "AAAABBBB");
    CHECK(find_gcode_thumbnail(g, 1000, t) && t.w == 600);
    // cut off in the middle (only the start of the file was read): the complete one is used
    std::string cut = g.substr(0, g.find("SkZJ"));
    GcodeThumbnail t2;
    CHECK(find_gcode_thumbnail(cut, 400, t2) && t2.w == 16);
    // wrong length in the header: ignored; none at all
    GcodeThumbnail t3;
    CHECK(!find_gcode_thumbnail("; thumbnail begin 16x16 99\n; AAAA\n; thumbnail end\n", 400, t3));
    CHECK(!find_gcode_thumbnail(";LAYER:0\nG1 X1\n", 400, t3));
    // Cura (thumbnail plug-in), CRLF line ends
    CHECK(find_gcode_thumbnail(";FLAVOR:Marlin\r\n; thumbnail begin 300x300 4\r\n; iVBO\r\n; thumbnail end\r\n", 400, t3) &&
          t3.base64 == "iVBO");
}

void test_multipart() {
    test_multipart_parse();
    test_thumbnails();
}
